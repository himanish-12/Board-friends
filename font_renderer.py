class BitmapFont:
    def __init__(self, size=20, bold=False):
        # Precise proportional scaling so text fits inside UI cards cleanly
        if size >= 28:
            self.scale = 3
        elif size >= 17:
            self.scale = 2
        else:
            self.scale = 2
        self.bold = bold and self.scale >= 3

    def render(self, text, antialias, color):
        text_u = str(text).upper()
        s = self.scale
        spacing = s
        extra_b = 1 if self.bold else 0

        widths = [len(GLYPHS.get(ch, GLYPHS[' '])[0]) * s + extra_b for ch in text_u]
        total_w = max(1, sum(widths) + spacing * max(0, len(text_u) - 1))
        total_h = 7 * s

        surf = pygame.Surface((total_w + 2, total_h + 2), pygame.SRCALPHA)

        ox = 0
        for idx, ch in enumerate(text_u):
            pattern = GLYPHS.get(ch, GLYPHS[' '])
            for r, row in enumerate(pattern):
                for c, val in enumerate(row):
                    if val == '1':
                        # Subtle drop shadow for readability
                        pygame.draw.rect(
                            surf,
                            (10, 12, 16, 150),
                            (ox + c * s + 1, r * s + 1, s + extra_b, s),
                        )
                        pygame.draw.rect(
                            surf, color, (ox + c * s, r * s, s + extra_b, s)
                        )
            ox += widths[idx] + spacing
        return surf


def get_font(name, size, bold=False):
    try:
        import pygame.font
        if not pygame.font.get_init():
            pygame.font.init()
        return pygame.font.SysFont(name, size, bold=bold)
    except Exception:
        return BitmapFont(size, bold=bold)
